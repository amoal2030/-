/**
 * تحليل المدخلات المحلية الذكي وإنتاج الفرص المتوافقة
 * @param {Object} userInput بيانات المستخدم
 * @returns {Array} قائمة بالفرص المخصصة
 */
function matchLocalOpportunities(userInput) {
  const text = (userInput.description || '').toLowerCase();
  const goal = userInput.goal || 'أريد دخلًا سريعًا';
  const hours = userInput.hours || '2';
  const budget = userInput.budget || '0';
  const level = userInput.level || 'مبتدئ';

  const scoredOpportunities = [];
  const seenIds = new Set();

  // فحص كل نمط ومدى تكرار الكلمات المفتاحية
  RESOURCE_PATTERNS.forEach(pattern => {
    let matchScore = 0;
    pattern.keywords.forEach(keyword => {
      if (text.includes(keyword.toLowerCase())) {
        matchScore += 3;
      }
    });

    if (matchScore > 0) {
      pattern.opportunities.forEach(opp => {
        if (!seenIds.has(opp.id)) {
          let totalScore = matchScore;

          // تعديل النقاط حسب الهدف المحدد
          if (goal.includes('دخل') && (opp.type === 'دخل' || opp.typeLabel.includes('دخل'))) {
            totalScore += 4;
          } else if (goal.includes('مشروع') && opp.type === 'مشروع') {
            totalScore += 4;
          } else if (goal.includes('خدمة') && opp.type === 'خدمة') {
            totalScore += 4;
          } else if (goal.includes('توفير') && (opp.type === 'توفير' || opp.cost.includes('مجاني'))) {
            totalScore += 3;
          } else if (goal.includes('مبتكرة') && (opp.type === 'إعادة استخدام' || opp.title.includes('إعادة'))) {
            totalScore += 4;
          }

          // ملاءمة مستوى الخبرة
          if (level === 'مبتدئ' && opp.difficulty === 'سهل') {
            totalScore += 2;
          } else if (level === 'متقدم' && opp.scalability.includes('عالية')) {
            totalScore += 2;
          }

          // تخصيص تعليل الملاءمة بناءً على مدخلات المستخدم
          const customizedOpp = JSON.parse(JSON.stringify(opp));
          customizedOpp.whyFit = `${customizedOpp.whyFit} تم تخصيص هذه الفرصة لتناسب وقتك (${hours} ساعات يوميًا) وميزانيتك (${budget}) ومستوى خبرتك (${level}).`;

          scoredOpportunities.push({ opp: customizedOpp, score: totalScore });
          seenIds.add(opp.id);
        }
      });
    }
  });

  // ترتيب الفرص تنازليًا حسب النقاط
  scoredOpportunities.sort((a, b) => b.score - a.score);
  let results = scoredOpportunities.map(item => item.opp);

  // إذا لم يتم العثور على ما يكفي (أقل من 3)، يتم دمج الفرص العامة الذكية
  if (results.length < 3) {
    GENERAL_FALLBACK_OPPORTUNITIES.forEach(fallbackOpp => {
      if (!seenIds.has(fallbackOpp.id) && results.length < 5) {
        const customizedFallback = JSON.parse(JSON.stringify(fallbackOpp));
        customizedFallback.whyFit = `${customizedFallback.whyFit} صُممت هذه الفكرة لتستغل مرونتك وتناسب ميزانية (${budget}) وساعات متاحة (${hours} ساعة).`;
        results.push(customizedFallback);
        seenIds.add(fallbackOpp.id);
      }
    });
  }

  // ضمان إرجاع من 3 إلى 5 فرص دائمًا
  return results.slice(0, Math.min(5, Math.max(3, results.length)));
}

/**
 * الدالة الرئيسية لتوليد الفرص: تدعم المحرك المحلي وتدعم الربط مع Gemini API
 * @param {Object} userInput - كائن يحتوي على:
 *   - description: نص يصف ما يملكه المستخدم
 *   - hours: عدد الساعات المتاحة يوميًا
 *   - budget: الميزانية المتاحة
 *   - goal: الهدف (دخل سريع، مشروع، خدمة، إلخ)
 *   - level: مستوى الخبرة (مبتدئ، متوسط، متقدم)
 * @returns {Promise<Array>} مصفوفة من كائنات الفرص المخصصة
 */
export async function generateOpportunities(userInput) {
  // فحص المدخلات
  if (!userInput || !userInput.description || !userInput.description.trim()) {
    throw new Error('يرجى كتابة وصف لما تملكه أو مهاراتك لاكتشاف الفرص.');
  }

  // إذا تم تفعيل API ولديه مفتاح أو خادم وسيط
  if (AI_CONFIG.useCloudAI && (AI_CONFIG.apiKey || AI_CONFIG.backendEndpoint)) {
    try {
      const cloudResults = await callGeminiAPI(userInput);
      if (cloudResults && cloudResults.length >= 3) {
        return cloudResults;
      }
    } catch (err) {
      console.warn('تعذر الاتصال بـ Gemini API السحابي، جاري التحويل تلقائيًا للمحرك المحلي الذكي:', err);
      // التراجع الآمن والسلس للمحرك المحلي
    }
  }

  // المحاكاة الواقعية لوقت المعالجة مع المحرك المحلي لإعطاء تجربة مستخدم سلسة
  await new Promise(resolve => setTimeout(resolve, 1400));
  return matchLocalOpportunities(userInput);
}

